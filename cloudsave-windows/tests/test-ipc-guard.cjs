const assert=require('node:assert/strict'),path=require('node:path'),{pathToFileURL}=require('node:url');
const {createSenderChecker,installIpcGuard}=require('../ipc-guard');
const appDir=path.join(__dirname,'..');
const isTrusted=createSenderChecker(appDir);
const appUrl=pathToFileURL(path.join(appDir,'index.html')).href;
const nestedUrl=pathToFileURL(path.join(appDir,'sub','preload.js')).href;
const outsideUrl=pathToFileURL(path.join(`${appDir}-backup`,'index.html')).href;
const windowOf=(url,destroyed=false)=>{const mainFrame={url};return {isDestroyed:()=>destroyed,mainFrame,getURL:()=>url};};
const from=(url,options={})=>{const sender=options.window||windowOf(url);return {sender,senderFrame:'senderFrame'in options?options.senderFrame:sender.mainFrame};};
(async()=>{
  assert.equal(isTrusted(from(appUrl)),true,'the application window must reach its own bridge');
  assert.equal(isTrusted(from(nestedUrl)),true,'files below the application directory must reach their own bridge');
  assert.equal(isTrusted(from('https://mirror.example/index.html')),false);
  assert.equal(isTrusted(from('about:blank')),false);
  assert.equal(isTrusted(from('file:///C:/Windows/notepad.exe')),false);
  assert.equal(isTrusted(from(outsideUrl)),false,'a same-prefix sibling folder is not the application directory');
  assert.equal(isTrusted(from('not a url')),false);
  assert.equal(isTrusted(from(appUrl,{window:windowOf(appUrl,true)})),false,'a destroyed window cannot call');
  assert.equal(isTrusted(from(appUrl,{senderFrame:{url:'https://mirror.example/inner.html'}})),false,'only the main frame may call');
  assert.equal(isTrusted({sender:windowOf(appUrl)}),true,'an older Electron without senderFrame falls back to the window url');
  assert.equal(isTrusted({sender:windowOf('https://mirror.example/')}),false);
  assert.equal(isTrusted({}),true,'a listener called in process has no Electron event to inspect');
  assert.equal(isTrusted(undefined),true,'and no event at all is an in-process call');
  const registered=new Map(),rejected=[];
  const ipcMain={handle(channel,listener){registered.set(channel,listener);return this;}};
  installIpcGuard(ipcMain,isTrusted,(channel,event)=>rejected.push([channel,event.senderFrame.url]));
  ipcMain.handle('runtime-version',()=>require('../package.json').version);
  ipcMain.handle('cloud-detail',async(_event,id,fresh)=>`${id}:${fresh?'fresh':'cache'}`);
  assert.equal(await registered.get('runtime-version')(from(appUrl)),require('../package.json').version);
  assert.equal(registered.get('runtime-version')(),require('../package.json').version,'in-process callers keep working');
  assert.equal(await registered.get('cloud-detail')(from(appUrl),'42',true),'42:fresh');
  assert.throws(()=>registered.get('cloud-detail')(from('https://mirror.example/'), '42'),/来源校验失败/,'Electron turns a synchronous throw into a rejected invoke');
  assert.deepEqual(rejected,[['cloud-detail','https://mirror.example/']]);
  assert.equal(registered.size,2);
  console.log('PASS the IPC guard admits only the application files in the main frame and rejects remote, sibling, sub-frame and destroyed senders');
})().catch(error=>{console.error(error);process.exitCode=1;});
